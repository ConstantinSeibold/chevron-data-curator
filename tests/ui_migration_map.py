"""The P3 migration contract: where every control in the pre-restructure UI ends up.

This is DATA, checked in next to the test that enforces it. Generated by auditing `index.html`
before the restructure began — 213 interactive controls across 15 tabs.

`DISPOSITION[legacy_id] = (kind, target_id, destination, note)`

  kind      MOVED   same control, new home
            MERGED  collapses into a shared control with others (the duplicated verbs)
            BECOMES replaced by a different affordance that does the same job
  target_id the id of the replacement, or None while its slice has not landed yet

The rule the test enforces: a legacy control must be EITHER still present in the served HTML (not
yet migrated) OR have a `target_id` that IS present (migrated). Never neither. With `target_id`
None, the legacy control must still exist — so a pane cannot be deleted before its replacement is
named. That makes "we dropped a feature" a test failure instead of a discovery months later.

Retiring something is still allowed. It just has to be written down here with a reason.
"""
